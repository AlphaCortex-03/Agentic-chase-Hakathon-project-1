"""
report_generator.py — Generates a downloadable incident post-mortem report.
"""

from datetime import datetime


def generate_postmortem_report(
    scenario_name: str,
    final_answer: str,
    steps: list,
) -> str:
    """
    Generates a formatted Markdown incident post-mortem report.

    Args:
        scenario_name: Name of the incident scenario.
        final_answer: The agent's final RCA summary.
        steps: List of agent steps (thought/action/observation dicts).

    Returns:
        A Markdown string ready to be downloaded.
    """
    now = datetime.now().strftime("%Y-%m-%d %H:%M:%S UTC")
    tool_calls = [s for s in steps if s.get("type") == "action"]
    num_tools = len(tool_calls)

    tools_section = []
    for i, step in enumerate(tool_calls, 1):
        tool_name = step.get("tool", "unknown")
        obs_preview = step.get("observation", "")[:300].replace("\n", "\n    ")
        tools_section.append(
            f"### Step {i} — `{tool_name}`\n"
            f"**Input**: `{step.get('tool_input', '')[:200]}`\n\n"
            f"**Result Preview**:\n```\n    {obs_preview}...\n```"
        )

    tools_md = "\n\n".join(tools_section)

    report = f"""# INCIDENT POST-MORTEM REPORT
**Generated by**: IncidentX Autonomous Incident Response Agent  
**Generated at**: {now}  
**Incident**: {scenario_name}  
**Agent Tool Calls**: {num_tools} diagnostic tools executed

---

## Executive Summary

{final_answer}

---

## Agent Investigation Trace

The IncidentX agent autonomously executed **{num_tools} diagnostic tool calls** in sequence
to identify the root cause, assess severity, retrieve remediation runbooks, and verify resolution.

{tools_md}

---

## Post-Mortem Action Items

| Priority | Action | Owner | Due |
|---|---|---|---|
| P0 | Apply long-term fix identified in runbook | On-call SRE | Within 24h |
| P1 | Add Prometheus alert for early warning | Platform team | Within 48h |
| P2 | Update incident runbook with new findings | SRE Lead | Within 1 week |
| P3 | Conduct blameless post-mortem with team | Engineering Manager | Within 1 week |

---

## Metrics

| Metric | Value |
|---|---|
| Mean Time to Detect (MTTD) | < 1 minute (automated) |
| Mean Time to Investigate (MTTI) | < 30 seconds (AI-powered) |
| Tools Used | {num_tools} |
| Agent | IncidentX v1.0 (Gemini 2.5 Flash) |

---

*This report was generated automatically by the IncidentX AI Agent.  
All tool executions are simulated for the hackathon demonstration.*
"""
    return report
